def get_skill_aliases():
    """Return a flat mapping of standard skill names to aliases."""
    aliases = {}

    for category_skills in SKILL_LIBRARY.values():
        for standard_name, alternative_names in category_skills.items():
            # Merge aliases if a skill appears in multiple categories.
            if standard_name in aliases:
                aliases[standard_name] = list(
                    dict.fromkeys(aliases[standard_name] + alternative_names)
                )
            else:
                aliases[standard_name] = list(alternative_names)

    return aliases
